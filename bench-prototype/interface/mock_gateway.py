#!/usr/bin/env python3
"""
Offline simulator of the UMSF gateway AG1 web interface.

Serves interface/dashboard.html (extracted verbatim from firmware/gateway/src/main.cpp)
and a synthetic /api endpoint with the same JSON structure as the gateway firmware,
so the dashboard can be inspected without ESP32 hardware.

All values are SYNTHETIC. They are generated by this script and are not readings
from the bench prototype.

Usage:
    python3 mock_gateway.py [--port 8000] [--scenario idle|impact|sos|linkloss]
then open http://127.0.0.1:8000

Scenarios:
    idle      all nodes online, no events (default)
    impact    after 20 s node A01 reports shock + pressure jump, wearable W02 an impact
    sos       after 20 s wearable W01 sends SOS
    linkloss  after 20 s node A01 stops reporting (link lost)

Requires only the Python standard library (3.8+).
"""
import argparse
import json
import math
import random
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

PAGE = (Path(__file__).resolve().parent / "dashboard.html").read_bytes()

# Bit masks as defined in firmware/gateway/src/main.cpp
F_SHOCK, F_TILT, F_LOUD, F_PRESSURE, F_GAS, F_HEAT, F_MOTION, F_VOICE, F_SOS, F_MQ_WARM = (1 << i for i in range(10))
S_MPU, S_BMP, S_DS, S_MIC, S_MQ, S_PIR = (1 << i for i in range(6))
W_FINGER, W_HR_VALID, W_HR_SYNTH, W_MOTION, W_IMPACT, W_SOS = (1 << i for i in range(6))
W_HR_ABN = 1 << 8
WS_PPG, WS_IMU, WS_TEMP = 1, 2, 4
HR_LOW, HR_HIGH = 45, 130
EV_ONLINE, EV_OFFLINE, EV_RESET, EV_W_SOS, EV_W_IMPACT, EV_W_HR = 20, 21, 22, 30, 31, 32

ZONES = {"A01": "Workshop 1 · north wing"}
PEOPLE = {"W01": "Responder 1", "W02": "Responder 2", "W03": "Responder 3"}


class Sim:
    def __init__(self, scenario, seed=1):
        self.scenario = scenario
        self.rng = random.Random(seed)
        self.t0 = time.monotonic()
        self.events = []
        self.reset_state()
        for i in list(ZONES) + list(PEOPLE):
            self.add_event(i, EV_ONLINE, None)

    def reset_state(self):
        self.node_latched = 0
        self.node_mx = {"g": 0.0, "pj": 0.0, "t": None, "mq": 0.0}
        self.wear_latched = {w: 0 for w in PEOPLE}
        self.wear_impact = {w: 0.0 for w in PEOPLE}
        self.prev = {}

    def now_ms(self):
        return int((time.monotonic() - self.t0) * 1000)

    def add_event(self, node, kind, value):
        self.events.insert(0, {"ms": self.now_ms(), "n": node, "k": kind, "v": value})
        del self.events[40:]

    def rising(self, key, flags):
        r = flags & ~self.prev.get(key, 0)
        self.prev[key] = flags
        return r

    def node(self, now):
        t = now / 1000
        active = t >= 20
        lost = self.scenario == "linkloss" and active
        age = int((t - 20) * 1000) if lost else self.rng.randint(0, 400)
        flags = F_MOTION if int(t) % 30 < 12 else 0
        pg, pj = 0.03 + self.rng.uniform(-0.01, 0.01), self.rng.uniform(0, 6)
        if self.scenario == "impact" and 20 <= t < 23:
            flags |= F_SHOCK | F_PRESSURE | F_LOUD
            pg, pj = 3.4, 180.0
        temp = 20.4 + 0.1 * math.sin(t / 30)
        mq = 0.93 + self.rng.uniform(-0.03, 0.03)
        if not lost:
            r = self.rising("A01", flags & 0x01FF)
            vals = {0: pg, 2: 900, 3: pj}
            for b in range(9):
                if r & (1 << b):
                    self.add_event("A01", b, vals.get(b))
            self.node_latched |= flags & 0x01FF & ~(F_MOTION | F_VOICE)
            self.node_mx["g"] = max(self.node_mx["g"], pg)
            self.node_mx["pj"] = max(self.node_mx["pj"], pj)
            self.node_mx["t"] = max(self.node_mx["t"] or temp, temp)
            self.node_mx["mq"] = max(self.node_mx["mq"], mq)
        elif not self.prev.get("A01_off"):
            self.prev["A01_off"] = 1
            self.add_event("A01", EV_OFFLINE, None)
        return {
            "id": "A01", "zone": ZONES["A01"], "online": not lost, "age": age,
            "pk": int(t), "lost": 0, "upS": int(t), "flags": flags, "latched": self.node_latched,
            "sensors": S_MPU | S_BMP | S_DS | S_MIC | S_MQ | S_PIR,
            "pg": round(pg, 2), "tilt": 0.1, "snd": 900 if flags & F_LOUD else self.rng.randint(100, 200),
            "mq": round(mq, 2), "mqb": 1.01, "t": round(temp, 1), "tb": 20.3,
            "p": round(1021.8 + self.rng.uniform(-0.05, 0.05), 1), "pj": round(pj),
            "mot": 0 if flags & F_MOTION else 5, "mx": dict(self.node_mx),
        }

    def wearable(self, wid, k, now):
        t = now / 1000
        flags = 0
        hr = 0
        if wid == "W02":  # synthetic pulse, flagged so the dashboard shows SIMULATED
            flags |= W_FINGER | W_HR_VALID | W_HR_SYNTH
            hr = round(74 + 4 * math.sin(t / 10))
        peak = 1.0 + self.rng.uniform(0, 0.05)
        if self.scenario == "impact" and wid == "W02" and 20 <= t < 23:
            flags |= W_IMPACT | W_MOTION
            peak = 5.2
        if self.scenario == "sos" and wid == "W01" and t >= 20:
            flags |= W_SOS
        if hr and not HR_LOW <= hr <= HR_HIGH:
            flags |= W_HR_ABN
        r = self.rising(wid, flags)
        if r & W_SOS:
            self.add_event(wid, EV_W_SOS, None)
        if r & W_IMPACT:
            self.add_event(wid, EV_W_IMPACT, peak)
        self.wear_latched[wid] |= flags & (W_IMPACT | W_SOS | W_HR_ABN)
        if flags & W_IMPACT:
            self.wear_impact[wid] = max(self.wear_impact[wid], peak)
        return {
            "id": wid, "name": PEOPLE[wid], "online": True, "age": self.rng.randint(0, 900),
            "pk": int(t) + 10 * k, "lost": 0, "upS": int(t), "flags": flags,
            "latched": self.wear_latched[wid], "sensors": WS_PPG | WS_IMU | WS_TEMP,
            "hr": hr, "beats": 8 if hr else 0, "pi": 0.4 if hr else 0.0,
            "t": round(20.3 + 0.1 * k, 1), "mot": 30,
            "mx": {"g": round(self.wear_impact[wid], 1), "hrMin": 70 if hr else 0, "hrMax": 78 if hr else 0},
        }

    def api(self):
        now = self.now_ms()
        nodes = [self.node(now)]
        people = [self.wearable(w, k, now) for k, w in enumerate(PEOPLE)]
        events = [{"ago": now - e["ms"], "n": e["n"], "k": e["k"], "v": e["v"]} for e in self.events]
        return {"gw": "AG1", "up": now, "hrLo": HR_LOW, "hrHi": HR_HIGH,
                "nodes": nodes, "people": people, "events": events}

    def reset(self):
        self.reset_state()
        self.events.clear()
        self.add_event("AG1", EV_RESET, None)


def make_handler(sim):
    class H(BaseHTTPRequestHandler):
        def _send(self, code, ctype, body):
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)

        def do_GET(self):
            if self.path == "/":
                self._send(200, "text/html; charset=utf-8", PAGE)
            elif self.path.startswith("/api"):
                self._send(200, "application/json", json.dumps(sim.api()).encode())
            else:
                self._send(404, "text/plain", b"not found")

        def do_POST(self):
            if self.path == "/reset":
                sim.reset()
                self._send(200, "application/json", b'{"ok":true}')
            else:
                self._send(404, "text/plain", b"not found")

        def log_message(self, *args):
            pass

    return H


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--port", type=int, default=8000)
    ap.add_argument("--scenario", choices=["idle", "impact", "sos", "linkloss"], default="idle")
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()
    sim = Sim(a.scenario, a.seed)
    srv = ThreadingHTTPServer(("127.0.0.1", a.port), make_handler(sim))
    print(f"UMSF gateway simulator (SYNTHETIC data, scenario={a.scenario}) at http://127.0.0.1:{a.port}")
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
