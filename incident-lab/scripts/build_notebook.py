ROOT = Path(__file__).resolve().parents[1]
PAYLOAD_FILES = ['.zenodo.json', 'CHANGELOG.md', 'CITATION.cff', 'LICENSE', 'README.md', 'START_HERE.txt',
                 'ZENODO_DESCRIPTION.txt', 'pyproject.toml', 'requirements.txt', 'requirements-optional.txt']
PAYLOAD_DIRS = ['data', 'docs', 'provenance', 'src', 'tests']


def build_payload() -> tuple[str, str, int]:
    files = [ROOT / f for f in PAYLOAD_FILES]
    for d in PAYLOAD_DIRS:
        files += [p for p in (ROOT / d).rglob('*') if p.is_file() and '__pycache__' not in p.parts]
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_LZMA) as archive:
        for p in sorted(files, key=lambda p: p.relative_to(ROOT).as_posix()):
            info = zipfile.ZipInfo(p.relative_to(ROOT).as_posix(), date_time=(2026, 10, 14, 0, 0, 0))
            info.compress_type = zipfile.ZIP_LZMA
            info.external_attr = 0o644 << 16
            archive.writestr(info, p.read_bytes())
    blob = buffer.getvalue()
    text = base64.b85encode(blob).decode()
    return hashlib.sha256(blob).hexdigest(), '\n'.join(textwrap.wrap(text, 120)), len(blob)


def md(text):
    return new_markdown_cell(textwrap.dedent(text).strip())


def code(text, **metadata):
    cell = new_code_cell(textwrap.dedent(text).strip())
    cell.metadata.update(metadata)
    return cell


